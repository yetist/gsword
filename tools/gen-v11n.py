"""Generate SWORD versification tables from the upstream canon headers.

Usage: tools/gen-v11n.py <sword-include-dir> <output.c>
"""

import os
import re
import sys

# Upper-case system name -> (header file, array suffix or None for base canon.h)
SYSTEMS = [
    ("KJV", "canon.h", ""),
    ("Leningrad", "canon_leningrad.h", "leningrad"),
    ("MT", "canon_mt.h", "mt"),
    ("KJVA", "canon_kjva.h", "kjva"),
    ("NRSV", "canon_nrsv.h", "nrsv"),
    ("NRSVA", "canon_nrsva.h", "nrsva"),
    ("Synodal", "canon_synodal.h", "synodal"),
    ("SynodalProt", "canon_synodalprot.h", "synodalProt"),
    ("Vulg", "canon_vulg.h", "vulg"),
    ("German", "canon_german.h", "german"),
    ("Luther", "canon_luther.h", "luther"),
    ("Catholic", "canon_catholic.h", "catholic"),
    ("Catholic2", "canon_catholic2.h", "catholic2"),
    ("LXX", "canon_lxx.h", "lxx"),
    ("Orthodox", "canon_orthodox.h", "orthodox"),
    ("Calvin", "canon_calvin.h", "calvin"),
    ("DarbyFr", "canon_darbyfr.h", "darbyfr"),
    ("Segond", "canon_segond.h", "segond"),
]


def parse_books(text, name):
    match = re.search(r"struct sbook " + re.escape(name) + r"\[\]\s*=\s*\{(.*?)\n\};", text, re.S)
    if not match:
        return None
    books = []
    for item in re.finditer(r'\{"([^"]*)",\s*"([^"]*)",\s*"([^"]*)",\s*(\d+)\}', match.group(1)):
        books.append((item.group(1), item.group(2), item.group(3), int(item.group(4))))
    return books


def parse_vm(text, name):
    match = re.search(r"int " + re.escape(name) + r"\[\]\s*=\s*\{(.*?)\n\};", text, re.S)
    if not match:
        return None
    body = re.sub(r"//[^\n]*", "", match.group(1))
    return [int(x) for x in re.findall(r"\b\d+\b", body)]


def parse_abbrevs(text):
    match = re.search(r"const struct abbrev builtin_abbrevs\[\]\s*=\s*\{(.*?)\n\};", text, re.S)
    if not match:
        raise SystemExit("cannot find builtin_abbrevs[]")
    return [(m.group(1), m.group(2)) for m in re.finditer(r'\{"([^"]*)",\s*"([^"]*)"\}', match.group(1))]


def c_string(value):
    return '"' + value.replace('\\', '\\\\').replace('"', '\\"') + '"'


def emit_books(out, cname, books):
    out.write(f"static const GswV11nBook {cname}[] = {{\n")
    for name, osis, abbr, chapmax in books:
        out.write(f"    {{ {c_string(name)}, {c_string(osis)}, {c_string(abbr)}, {chapmax} }},\n")
    out.write("    { NULL, NULL, NULL, 0 }\n};\n\n")


def emit_vm(out, cname, vm):
    out.write(f"static const gint {cname}[] = {{\n")
    for i in range(0, len(vm), 16):
        out.write("    " + ", ".join(str(x) for x in vm[i:i + 16]) + ",\n")
    out.write("};\n\n")


def main():
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)

    include_dir = sys.argv[1]
    dest = sys.argv[2]

    canon = open(os.path.join(include_dir, "canon.h"), encoding="utf-8").read()
    abbrevs = open(os.path.join(include_dir, "canon_abbrevs.h"), encoding="utf-8").read()
    kjv_ot = parse_books(canon, "otbooks")
    kjv_nt = parse_books(canon, "ntbooks")
    kjv_vm = parse_vm(canon, "vm")
    abbr = parse_abbrevs(abbrevs)

    systems = []
    arrays = []

    for index, (name, filename, suffix) in enumerate(SYSTEMS):
        path = os.path.join(include_dir, filename)
        if not os.path.exists(path):
            continue
        text = open(path, encoding="utf-8").read()

        if suffix:
            parsed_ot = parse_books(text, f"otbooks_{suffix}")
            parsed_nt = parse_books(text, f"ntbooks_{suffix}")
            if parsed_ot is None:
                parsed_ot = [("", "", "", 0)] if "use otbooks_null" in text else kjv_ot
            if parsed_nt is None:
                parsed_nt = [("", "", "", 0)] if "use ntbooks_null" in text else kjv_nt
            ot = parsed_ot
            nt = parsed_nt
            vm_name = f"vm_{suffix}"
            vm = parse_vm(text, vm_name)
            if vm is None:
                print(f"warning: no {vm_name} in {filename}", file=sys.stderr)
                continue
            ot_name = f"gsw_{suffix}_ot"
            nt_name = f"gsw_{suffix}_nt"
            vm_cname = f"gsw_{suffix}_verse_max"
        else:
            ot = kjv_ot
            nt = kjv_nt
            vm = kjv_vm
            ot_name = "gsw_kjv_ot"
            nt_name = "gsw_kjv_nt"
            vm_cname = "gsw_kjv_verse_max"

        arrays.append(("books", ot_name, ot))
        arrays.append(("books", nt_name, nt))
        arrays.append(("vm", vm_cname, vm))

        systems.append((name, ot_name, nt_name, vm_cname))

    with open(dest, "w", encoding="utf-8") as out:
        out.write("/* Generated by tools/gen-v11n.py from SWORD canon headers. Do not edit. */\n")
        out.write('#include "gsw-versification-data.h"\n\n')

        emitted = set()
        for kind, cname, data in arrays:
            if cname in emitted:
                continue
            emitted.add(cname)
            if kind == "books":
                if cname in ("gsw_kjv_ot", "gsw_kjv_nt"):
                    # Public only for the KJV base; other systems may reuse it.
                    out.write(f"const GswV11nBook {cname}[] = {{\n")
                    for bname, osis, abbr_name, chapmax in data:
                        out.write(f"    {{ {c_string(bname)}, {c_string(osis)}, {c_string(abbr_name)}, {chapmax} }},\n")
                    out.write("    { NULL, NULL, NULL, 0 }\n};\n\n")
                else:
                    emit_books(out, cname, data)
            else:
                out.write(f"const gint {cname}[] = {{\n")
                for i in range(0, len(data), 16):
                    out.write("    " + ", ".join(str(x) for x in data[i:i + 16]) + ",\n")
                out.write("};\n\n")

        out.write("const GswV11nSystemData gsw_v11n_systems[] = {\n")
        for name, ot_name, nt_name, vm_cname in systems:
            out.write(f"    {{ {c_string(name)}, {ot_name}, {nt_name}, {vm_cname} }},\n")
        out.write("    { NULL, NULL, NULL, NULL }\n};\n\n")

        out.write("const GswV11nAbbrev gsw_builtin_abbrevs[] = {\n")
        for key, osis in abbr:
            if key == "" and osis == "":
                break
            out.write(f"    {{ {c_string(key)}, {c_string(osis)} }},\n")
        out.write("    { NULL, NULL }\n};\n\n")
        out.write("const guint gsw_builtin_abbrevs_count = G_N_ELEMENTS(gsw_builtin_abbrevs) - 1;\n")


if __name__ == "__main__":
    main()
